            'addresses' => ['مركز المدينة', 'الشارع الرئيسي', 'وسط المدينة', 'قرب السوق']
        ],
    ];

    public function run()
    {
        $citizens = User::where('role', 'citizen')->get();
        $categories = ['infrastructure', 'electricity', 'roads', 'sanitation', 'building', 'other'];
        // جميع حالات البلاغات
        $statuses = ['pending', 'processing', 'resolved', 'on-hold', 'rejected'];

        if ($citizens->isEmpty()) {
            $this->command->warn('⚠️  لا يوجد مواطنين في قاعدة البيانات. يرجى تشغيل UsersSeeder أولاً.');
            return;
        }

        $created = 0;
        $failed = 0;
        $statusCounts = [
            'pending' => 0,
            'processing' => 0,
            'resolved' => 0,
            'on-hold' => 0,
            'rejected' => 0
        ];

        foreach ($citizens as $index => $citizen) {
            // الحصول على محافظة المواطن
            $citizenGovernorate = $citizen->governorate ?? 'دمشق';
            
            // الحصول على معلومات المحافظة
            $governorateInfo = $this->governorates[$citizenGovernorate] ?? $this->governorates['دمشق'];
            
            // الحصول على بلدية المحافظة
            $municipality = Municipality::where('name', $governorateInfo['name'])->first();
            
            if (!$municipality) {
                // إذا لم نجد البلدية، نبحث عن أي بلدية في نفس المحافظة
                $municipality = Municipality::where('governorate', $citizenGovernorate)->first();
            }
            
            if (!$municipality) {
                // إذا لم نجد، نأخذ أول بلدية
                $municipality = Municipality::first();
            }

            if (!$municipality) {
                $this->command->error("❌ لم يتم العثور على أي بلدية للمواطن: {$citizen->name}");
                $failed += 2;
                continue;
            }

            // إنشاء بلاغين لكل مواطن مع توزيع الحالات
            for ($i = 0; $i < 2; $i++) {
                // اختيار فئة عشوائية
                $category = $categories[array_rand($categories)];
                
                // اختيار قالب من الفئة
                $templates = $this->reportTemplates[$category];
                $template = $templates[array_rand($templates)];
                
                // توزيع الحالات بشكل متنوع
                // أول مواطن: pending, processing
                // ثاني مواطن: processing, resolved
                // ثالث مواطن: resolved, on-hold
                // رابع مواطن: on-hold, rejected
                // وهكذا...
                $statusIndex = ($index * 2 + $i) % count($statuses);
                $status = $statuses[$statusIndex];
                $statusCounts[$status]++;
                
                // إضافة تعليق رسمي واقعي حسب الحالة
                $officialComment = null;
                if ($status === 'processing') {
                    $comments = [
                        'فريق الصيانة يعمل على حل المشكلة. تم تنظيف 60% من المنطقة.',
                        'تم تحديد موقع المشكلة. فريق الصيانة في الطريق لإصلاح المشكلة.',
                        'جاري إصلاح المحول الرئيسي وتعزيز الشبكة. سيتم استكمال العمل خلال أسبوع.',
                        'فريق الصيانة يعمل على حل المشكلة. سيتم استكمال العمل قريباً.',
                        'تم إرسال فريق فني لفحص المشكلة. جاري اتخاذ الإجراءات اللازمة.',
                    ];
                    $officialComment = $comments[array_rand($comments)];
                } elseif ($status === 'resolved') {
                    $comments = [
                        'تم حل المشكلة بنجاح. المنطقة آمنة الآن.',
                        'تم إصلاح المشكلة بالكامل. تم تنظيف المنطقة وإزالة جميع المخاطر.',
                        'تم حل المشكلة. تم إصلاح الخط وإعادة الخدمة بشكل كامل.',
                        'تم إزالة المشكلة. المنطقة نظيفة وآمنة الآن.',
                        'تم حل المشكلة بنجاح. تم إصلاح جميع الأضرار.',
                    ];
                    $officialComment = $comments[array_rand($comments)];
                } elseif ($status === 'on-hold') {
                    $comments = [
                        'تم تأجيل المعالجة بسبب الحاجة لموافقات إضافية من الجهات المختصة.',
                        'البلاغ قيد الانتظار بسبب نقص الموارد المالية المخصصة للمشروع.',
                        'تم تأجيل المعالجة مؤقتاً بسبب ظروف الطقس غير المناسبة.',
                        'البلاغ في قائمة الانتظار بسبب أولويات أخرى أكثر إلحاحاً.',
                        'تم تأجيل المعالجة حتى إتمام الدراسات الفنية المطلوبة.',
                    ];
                    $officialComment = $comments[array_rand($comments)];
                } elseif ($status === 'rejected') {
                    $comments = [
                        'تم رفض البلاغ لأنه لا يندرج ضمن اختصاصات البلدية.',
                        'البلاغ مرفوض بسبب عدم توفر المعلومات الكافية لتحديد موقع المشكلة.',
                        'تم رفض البلاغ لأنه يتطلب تدخل جهات أخرى غير البلدية.',
                        'البلاغ مرفوض بسبب عدم وجود مخالفة فعلية في الموقع المذكور.',
                        'تم رفض البلاغ لأنه تم حله مسبقاً من قبل الجهات المختصة.',
                    ];
                    $officialComment = $comments[array_rand($comments)];
                }

                // إحداثيات قريبة من البلدية مع تغيير بسيط
                $lat = $municipality->lat + (rand(-100, 100) / 1000); // تغيير بسيط
                $lng = $municipality->lng + (rand(-100, 100) / 1000);

                // عنوان واقعي بناء على المحافظة
                $addressPart = $governorateInfo['addresses'][array_rand($governorateInfo['addresses'])];
                $address = "{$citizenGovernorate} - {$municipality->name} - {$addressPart}";

                // تاريخ عشوائي خلال آخر 30 يوم
                $daysAgo = rand(1, 30);
                $createdAt = Carbon::now()->subDays($daysAgo);
                $updatedAt = $status !== 'pending' ? $createdAt->copy()->addDays(rand(1, min($daysAgo, 10))) : $createdAt;

                try {
                    Report::create([
                        'title' => $template['title'],
                        'description' => $template['description'],
                        'category' => $category,
                        'priority' => $template['priority'],
                        'status' => $status,
                        'location_lat' => $lat,
                        'location_lng' => $lng,
                        'address' => $address,
                        'user_id' => $citizen->id,
                        'municipality_id' => $municipality->id,
                        'is_anonymous' => false,
                        'official_comment' => $officialComment,
                        'images' => [
                            'https://images.pexels.com/photos/259588/pexels-photo-259588.jpeg?auto=compress&cs=tinysrgb&w=800',
                            'https://images.pexels.com/photos/2219024/pexels-photo-2219024.jpeg?auto=compress&cs=tinysrgb&w=800'
                        ],
                        'created_at' => $createdAt,
                        'updated_at' => $updatedAt,
                    ]);
                    $created++;
                } catch (\Exception $e) {
                    $this->command->error("❌ خطأ في إنشاء بلاغ للمواطن {$citizen->name}: " . $e->getMessage());
                    $failed++;
                }
            }
        }

        $this->command->info("✅ تم إنشاء {$created} بلاغ بنجاح!");
        if ($failed > 0) {
            $this->command->warn("⚠️  فشل في إنشاء {$failed} بلاغ!");
        }
        
        // عرض إحصائيات الحالات
        $this->command->info("\n📊 إحصائيات حالات البلاغات:");
        $this->command->info("   • قيد الانتظار (pending): {$statusCounts['pending']}");
        $this->command->info("   • قيد المعالجة (processing): {$statusCounts['processing']}");
        $this->command->info("   • تم الحل (resolved): {$statusCounts['resolved']}");
        $this->command->info("   • مؤجل (on-hold): {$statusCounts['on-hold']}");
        $this->command->info("   • مرفوض (rejected): {$statusCounts['rejected']}");
    }
}
